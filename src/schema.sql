-- Mini_LinkAI PHP 版：全量表结构（对应原仓库 0001~0019 迁移的核心模型）
-- MySQL 8.0 / utf8mb4；时间统一 UTC 存储，配额日切用 Asia/Shanghai 计算

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NULL UNIQUE,
  phone VARCHAR(32) NULL UNIQUE,
  nickname VARCHAR(64) NOT NULL DEFAULT '成员',
  avatar VARCHAR(255) NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('admin','member') NOT NULL DEFAULT 'member',
  status ENUM('active','banned') NOT NULL DEFAULT 'active',
  must_change_password TINYINT(1) NOT NULL DEFAULT 0,
  token_version INT NOT NULL DEFAULT 1,
  theme VARCHAR(16) NOT NULL DEFAULT 'light',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS jwt_blacklist (
  jti CHAR(36) PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  expires_at DATETIME NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_jb_user (user_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS settings (
  `key` VARCHAR(64) PRIMARY KEY,
  `value` JSON NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS channels (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(96) NOT NULL,
  protocol ENUM('openai_compatible','anthropic','gemini') NOT NULL DEFAULT 'openai_compatible',
  base_url VARCHAR(512) NOT NULL,
  api_key_enc TEXT NULL,
  api_key_hint VARCHAR(16) NOT NULL DEFAULT '****',
  params JSON NULL,
  priority INT NOT NULL DEFAULT 0,
  weight INT NOT NULL DEFAULT 100,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  cooldown_until DATETIME NULL,
  fail_count INT NOT NULL DEFAULT 0,
  last_error VARCHAR(512) NULL,
  last_checked_at DATETIME NULL,
  version INT NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_ch_name (name),
  INDEX idx_ch_route (enabled, priority, weight)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS channel_models (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  channel_id BIGINT UNSIGNED NOT NULL,
  upstream_model VARCHAR(190) NOT NULL,
  synced_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_cm (channel_id, upstream_model),
  CONSTRAINT fk_cm_ch FOREIGN KEY (channel_id) REFERENCES channels(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS models (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  public_name VARCHAR(96) NOT NULL UNIQUE,
  display_name VARCHAR(96) NOT NULL,
  tier ENUM('premium','fast','standard') NOT NULL DEFAULT 'standard',
  context_limit INT NOT NULL DEFAULT 32768,
  price_input DECIMAL(10,4) NOT NULL DEFAULT 0,
  price_output DECIMAL(10,4) NOT NULL DEFAULT 0,
  is_default TINYINT(1) NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS model_channels (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  model_id BIGINT UNSIGNED NOT NULL,
  channel_id BIGINT UNSIGNED NOT NULL,
  upstream_model VARCHAR(190) NOT NULL,
  weight INT NOT NULL DEFAULT 100,
  UNIQUE KEY uk_mc (model_id, channel_id),
  CONSTRAINT fk_mc_model FOREIGN KEY (model_id) REFERENCES models(id) ON DELETE CASCADE,
  CONSTRAINT fk_mc_ch FOREIGN KEY (channel_id) REFERENCES channels(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS invite_codes (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE,
  created_by BIGINT UNSIGNED NULL,
  max_uses INT NOT NULL DEFAULT 1,
  used_count INT NOT NULL DEFAULT 0,
  revoked TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS conversations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(190) NOT NULL DEFAULT '新会话',
  pinned TINYINT(1) NOT NULL DEFAULT 0,
  deleted_at DATETIME NULL,
  active_generation CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX idx_conv_user (user_id, deleted_at, pinned, updated_at),
  CONSTRAINT fk_conv_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS messages (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  conversation_id BIGINT UNSIGNED NOT NULL,
  role ENUM('user','assistant','system') NOT NULL,
  content MEDIUMTEXT NOT NULL,
  model_id BIGINT UNSIGNED NULL,
  tokens_in INT NOT NULL DEFAULT 0,
  tokens_out INT NOT NULL DEFAULT 0,
  generation_id CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_msg_conv (conversation_id, id),
  CONSTRAINT fk_msg_conv FOREIGN KEY (conversation_id) REFERENCES conversations(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS quota_daily (
  user_id BIGINT UNSIGNED NOT NULL,
  quota_date DATE NOT NULL,
  msg_count INT NOT NULL DEFAULT 0,
  token_count INT NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, quota_date)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS usage_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  conversation_id BIGINT UNSIGNED NULL,
  room_id BIGINT UNSIGNED NULL,
  model_id BIGINT UNSIGNED NULL,
  channel_id BIGINT UNSIGNED NULL,
  generation_id CHAR(36) NOT NULL,
  status ENUM('pending','settled','refunded','failed') NOT NULL DEFAULT 'pending',
  tokens_in INT NOT NULL DEFAULT 0,
  tokens_out INT NOT NULL DEFAULT 0,
  cost DECIMAL(12,6) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  settled_at DATETIME NULL,
  INDEX idx_usage_status (status, created_at),
  INDEX idx_usage_user (user_id, created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ai_jobs (
  generation_id CHAR(36) PRIMARY KEY,
  conversation_id BIGINT UNSIGNED NULL,
  room_id BIGINT UNSIGNED NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  status ENUM('running','done','cancelled','failed') NOT NULL DEFAULT 'running',
  cancel_requested TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS rooms (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(96) NOT NULL,
  description VARCHAR(255) NOT NULL DEFAULT '',
  owner_id BIGINT UNSIGNED NOT NULL,
  access_type ENUM('public','private') NOT NULL DEFAULT 'public',
  member_count INT NOT NULL DEFAULT 0,
  archived TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_room_name (name)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS room_members (
  room_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  role ENUM('owner','member') NOT NULL DEFAULT 'member',
  joined_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (room_id, user_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS room_messages (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  room_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NULL,
  nickname VARCHAR(64) NOT NULL DEFAULT 'AI',
  kind ENUM('user','ai','system') NOT NULL DEFAULT 'user',
  content MEDIUMTEXT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_rm (room_id, id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS friends (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  friend_id BIGINT UNSIGNED NOT NULL,
  status ENUM('pending','accepted','rejected') NOT NULL DEFAULT 'pending',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_fr (user_id, friend_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS dm_messages (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  from_id BIGINT UNSIGNED NOT NULL,
  to_id BIGINT UNSIGNED NOT NULL,
  content TEXT NOT NULL,
  read_at DATETIME NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_dm (from_id, to_id, id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS templates (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(96) NOT NULL,
  content TEXT NOT NULL,
  scope ENUM('system','user') NOT NULL DEFAULT 'user',
  owner_id BIGINT UNSIGNED NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS feedback (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  message_id BIGINT UNSIGNED NULL,
  rating TINYINT NOT NULL,
  comment VARCHAR(500) NOT NULL DEFAULT '',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_fb_msg (message_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS experiments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(96) NOT NULL UNIQUE,
  variant_a INT NOT NULL DEFAULT 50,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS uploads (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  filename VARCHAR(255) NOT NULL,
  stored_path VARCHAR(512) NOT NULL,
  mime VARCHAR(128) NOT NULL DEFAULT 'application/octet-stream',
  size_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS shares (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  token VARCHAR(48) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(190) NOT NULL DEFAULT '分享的对话',
  payload MEDIUMTEXT NOT NULL,
  expires_at DATETIME NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  actor_id BIGINT UNSIGNED NULL,
  action VARCHAR(96) NOT NULL,
  target_type VARCHAR(64) NOT NULL DEFAULT '',
  target_id VARCHAR(64) NOT NULL DEFAULT '',
  detail JSON NULL,
  ip VARCHAR(64) NOT NULL DEFAULT '',
  trace_id CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_audit (actor_id, created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS idempotency (
  idem_key VARCHAR(128) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  response MEDIUMTEXT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (idem_key, user_id)
) ENGINE=InnoDB;
